<script setup lang="ts">
/**
 * The clearance drawing (signature moment 4): one wheel in its wheel arch, seen from behind — what
 * you see standing behind the car looking at a rear wheel. Across is sideways, inside (the strut,
 * *Federbein*) on the left and outside (the fender, *Kotflügel*) on the right; up is height.
 *
 * - The tyre is a rounded shape as wide as its nominal section width and as high as the tyre; the
 *   rim inside it is as wide as the rim and as high as its diameter. Both wheels are drawn to one
 *   true scale, so a bigger tyre looks bigger.
 * - The mounting face (Anlagefläche, dash-dot) is the car's: one line for both wheels. A positive
 *   ET puts the rim's centre plane that far inboard of it; the tyre is centred on that plane.
 * - The strut and the fender are schematic (their place depends on the car) and the same for both.
 * - The current wheel is dashed, the new one solid and tinted.
 * - Two arrows under the wheels run from each current rim edge to the new one, exactly as long as
 *   the model's shift; an edge that moves by no whole millimetre has no arrow and reads
 *   *unverändert*.
 *
 * Everything is generated by `lib/felgenGeometry` (`rearScene`) from the same `FelgenModel` whose
 * texts are the labels (ACCURACY.md §6). The labels are HTML: the part names in a row above the
 * sheet, split between the strut and the fender; each arrow's label in a row of its own below it,
 * at the arrow's middle, shifted by the same fraction of its own width (`left: f; translateX(−f)`).
 * So a label stays inside the drawing's width, may wrap, and can never overlap another label or
 * the drawing, at any width. Ink and line colours only: nothing here is a verdict.
 *
 * A tyre and a rim that do not belong together (`implausible`) are not drawn at all — the results
 * say so in a sentence instead.
 *
 * Motion: when a value changes, the two wheels' numbers are tweened over `--d-2` with `--ease-std`
 * in a requestAnimationFrame loop and the scene is rebuilt from the in-between numbers. Labels and
 * the aria-label read the target values straight away. Under reduced motion, and on the server,
 * the drawing rests in its end state.
 */

import { computed, onBeforeUnmount, onMounted, ref, watch } from 'vue'
import ValueText from './ValueText.vue'
import { felgenModel, REAR, rearFrame, rearScene, twoHeaded, wholeMmText, type RearFrame, type SetupSide, type WheelFrame, type WheelSetup } from '../../lib/felgenGeometry'
import { etLabel, jLabel, setupLine } from '../../lib/rechner'

const props = defineProps<{ current: WheelSetup; next: WheelSetup }>()

const model = computed(() => felgenModel(props.current, props.next))
const plausible = computed(() => model.value.implausible.length === 0)
const target = computed(() => rearFrame(model.value))

/* ── The morph ─────────────────────────────────────────────────────────────────── */

const SIDE_KEYS: SetupSide[] = ['current', 'next']
const FRAME_KEYS: (keyof WheelFrame)[] = ['centreX', 'tyreWidthMm', 'diameterMm', 'rimWidthMm', 'rimDiameterMm']

function cloneFrame(f: RearFrame): RearFrame {
    return { current: { ...f.current }, next: { ...f.next } }
}

function sameFrame(a: RearFrame, b: RearFrame): boolean {
    return SIDE_KEYS.every((side) => FRAME_KEYS.every((key) => a[side][key] === b[side][key]))
}

function lerpFrame(from: RearFrame, to: RearFrame, t: number): RearFrame {
    const out = cloneFrame(to)

    for (const side of SIDE_KEYS) {
        for (const key of FRAME_KEYS) {
            out[side][key] = from[side][key] + (to[side][key] - from[side][key]) * t
        }
    }

    return out
}

/** The CSS timing function as a number-to-number function (the usual Newton–Raphson on x). */
function cubicBezier(x1: number, y1: number, x2: number, y2: number): (t: number) => number {
    const a = (p1: number, p2: number) => 1 - 3 * p2 + 3 * p1
    const b = (p1: number, p2: number) => 3 * p2 - 6 * p1
    const c = (p1: number) => 3 * p1
    const at = (t: number, p1: number, p2: number) => ((a(p1, p2) * t + b(p1, p2)) * t + c(p1)) * t
    const slope = (t: number, p1: number, p2: number) => 3 * a(p1, p2) * t * t + 2 * b(p1, p2) * t + c(p1)

    return (x) => {
        if (x <= 0) {
            return 0
        }

        if (x >= 1) {
            return 1
        }

        let t = x

        for (let i = 0; i < 8; i++) {
            const dx = at(t, x1, x2) - x
            const d = slope(t, x1, x2)

            if (Math.abs(dx) < 1e-5 || d === 0) {
                break
            }

            t -= dx / d
        }

        return at(t, y1, y2)
    }
}

function parseMs(value: string): number | null {
    const match = /^\s*([\d.]+)\s*(ms|s)\s*$/.exec(value)

    if (match === null || match[1] === undefined) {
        return null
    }

    const n = Number(match[1])

    return Number.isFinite(n) ? (match[2] === 's' ? n * 1000 : n) : null
}

function parseBezier(value: string): ((t: number) => number) | null {
    const match = /cubic-bezier\(([^)]+)\)/.exec(value)
    const parts = match?.[1]?.split(',').map((v) => Number(v.trim())) ?? []

    if (parts.length !== 4 || parts.some((v) => !Number.isFinite(v))) {
        return null
    }

    return cubicBezier(parts[0] as number, parts[1] as number, parts[2] as number, parts[3] as number)
}

const frame = ref<RearFrame>(cloneFrame(target.value))
/* No motion until we are on a client that has not asked for stillness. */
const motion = ref(false)
let raf = 0
let duration = 200
let ease = cubicBezier(0.4, 0, 0.2, 1)

onMounted(() => {
    motion.value = !(window.matchMedia?.('(prefers-reduced-motion: reduce)').matches ?? false)

    const style = getComputedStyle(document.documentElement)
    duration = parseMs(style.getPropertyValue('--d-2')) ?? duration
    ease = parseBezier(style.getPropertyValue('--ease-std')) ?? ease
})

function stop(): void {
    if (raf !== 0 && typeof cancelAnimationFrame === 'function') {
        cancelAnimationFrame(raf)
    }

    raf = 0
}

watch(target, (to) => {
    if (sameFrame(to, frame.value)) {
        return
    }

    stop()

    // Nothing to morph from or to while a comparison is not drawn: the drawing appears at rest.
    if (!motion.value || !plausible.value || typeof requestAnimationFrame !== 'function') {
        frame.value = cloneFrame(to)

        return
    }

    const from = cloneFrame(frame.value)
    const started = performance.now()

    const step = (now: number): void => {
        const t = Math.min(1, (now - started) / duration)
        frame.value = lerpFrame(from, to, ease(t))
        raf = t < 1 ? requestAnimationFrame(step) : 0
    }

    raf = requestAnimationFrame(step)
})

onBeforeUnmount(stop)

/* ── What is drawn (tweened) and what is written (the model, at once) ──────────── */

const scene = computed(() => rearScene(frame.value, model.value))
const resting = computed(() => rearScene(target.value, model.value))

function clampPercent(fraction: number): number {
    return Math.round(Math.min(Math.max(fraction, 0), 1) * 1000) / 10
}

/** `left: f; translateX(−f)` keeps a label inside its row with its anchor inside the label. */
function at(fraction: number): Record<string, string> {
    const f = clampPercent(fraction)

    return { left: `${f}%`, transform: `translateX(-${f}%)` }
}

/* The part names share one row, split halfway between the strut and the fender. */
const parts = computed(() => {
    const strut = resting.value.strut.anchor
    const fender = resting.value.fender.anchor
    const split = (strut + fender) / 2

    return {
        row: { gridTemplateColumns: `${clampPercent(split)}% minmax(0, 1fr)` },
        strut: at(strut / split),
        fender: at((fender - split) / (1 - split)),
    }
})

const labels = computed(() => ({
    outer: at(resting.value.outer.anchor),
    inner: at(resting.value.inner.anchor),
}))

const legend = computed(() => ({
    current: setupLine(props.current),
    next: setupLine(props.next),
}))

/* The wheel's middle from outside: five screws on the bolt circle, the bore inside it — a schematic, in its own units. */
const FRONT = { size: 200, c: 100, disc: 92, lk: 56, hole: 9, bore: 27, tagY: 186 } as const

const holes = Array.from({ length: 5 }, (_, i) => {
    const angle = ((-90 + i * 72) * Math.PI) / 180

    return { x: Math.round((FRONT.c + FRONT.lk * Math.cos(angle)) * 100) / 100, y: Math.round((FRONT.c + FRONT.lk * Math.sin(angle)) * 100) / 100 }
})

/* The bolt circle's diameter, across the middle, between two screws. */
const lkDim = twoHeaded(FRONT.c - FRONT.lk, FRONT.c + FRONT.lk, FRONT.c)

/*
 * The new wheel's own measures, written inside the sheet beside the lines they name (#11): the sheet scales as one, so
 * a label keeps its place against its line at any width. ET 0 has no dimension — the two lines are one.
 */
const measures = computed(() => ({
    et: etLabel(props.next.etMm),
    width: `${jLabel(props.next.widthIn)} = ${wholeMmText(model.value.next.rimWidthMm)}`,
}))

const description = computed(
    () =>
        `Blick von hinten auf ein Rad im Radhaus, die Felge im Schnitt, rechnerisch. ${model.value.outer.text}. ${model.value.inner.text}. ` +
        `Neue Felge: Einpresstiefe ${measures.value.et}, der Abstand von der Felgenmitte zur Anlagefläche; Maulweite ${measures.value.width}. ` +
        'Daneben die Radmitte von außen mit Lochkreis und Mittenlochbohrung. Federbein, Kotflügel, Radschüssel und Schrauben schematisch.'
)
</script>

