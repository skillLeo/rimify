import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { OUT, type Finding } from './support';

/**
 * Every project's findings merged into one line each — `severity · page · width · what · expected` — the format of
 * docs/reviews/sweep-storefront.md, most severe first. The same finding at both widths is one line with both.
 */
export default async function globalTeardown(): Promise<void> {
    if (!existsSync(OUT)) {
        return;
    }

    const merged = new Map<string, Finding & { widths: Set<string>; shots: Set<string> }>();

    for (const file of readdirSync(OUT).filter((f) => f.endsWith('.jsonl'))) {
        for (const line of readFileSync(join(OUT, file), 'utf8').split('\n')) {
            if (line.trim() === '') {
                continue;
            }

            const finding = JSON.parse(line) as Finding;
            const key = `${finding.severity}|${finding.page}|${finding.what}`;
            const entry = merged.get(key) ?? { ...finding, widths: new Set<string>(), shots: new Set<string>() };

            entry.widths.add(finding.width);

            if (finding.shot) {
                entry.shots.add(finding.shot);
            }

            merged.set(key, entry);
        }
    }

    const rows = [...merged.values()].sort((a, b) => a.severity.localeCompare(b.severity) || a.page.localeCompare(b.page));
    const counts = ['S1', 'S2', 'S3', 'S4'].map((s) => `${s} ${rows.filter((r) => r.severity === s).length}`).join(' · ');
    const lines = rows.map((r) => {
        const shots = r.shots.size ? ` (${[...r.shots].join(', ')})` : '';

        return `${r.severity} · ${r.page} · ${[...r.widths].sort().join('/')} · ${r.what}${shots} · ${r.expected}`;
    });

    // What each page said where the walk read it (the panel texts, the options, the counts): evidence, not findings.
    const observations = readdirSync(OUT)
        .filter((f) => f.startsWith('observations-'))
        .flatMap((f) => [``, `### ${f.replace(/^observations-|\.txt$/g, '')}`, '', ...readFileSync(join(OUT, f), 'utf8').trim().split('\n').map((l) => `- ${l}`)]);

    writeFileSync(
        join(OUT, 'live-findings.md'),
        [
            '# Storefront sweep — live run',
            '',
            `${new Date().toISOString()} · ${process.env.SWEEP_BASE_URL ?? 'https://rimify.skillleo.com'} · ${counts}`,
            '',
            'Format: `severity · page · width · what (screenshot) · expected`. Generated by scripts/qa/sweep-storefront.',
            '',
            ...lines,
            '',
            '## Observations',
            ...observations,
            '',
        ].join('\n'),
    );

    console.log(`sweep: ${counts} → ${join(OUT, 'live-findings.md')}`);
}
